import { useMemo } from 'react';
import { Link } from 'react-router-dom';
import { Trophy, ArrowRight, Award, GraduationCap, Compass, Printer, Info, TrendingUp, Briefcase } from 'lucide-react';
import { AppShell } from '@/components/layout/AppShell';
import { Card, CardHeader } from '@/components/ui/Card';
import { Badge } from '@/components/ui/Badge';
import { BarChart } from '@/components/charts/BarChart';
import { DonutChart } from '@/components/charts/DonutChart';
import { useAssessment } from '@/context/AssessmentContext';
import { useProfile } from '@/context/ProfileContext';
import { useThresholds } from '@/context/ThresholdContext';
import { useAuth } from '@/context/AuthContext';
import { categorizeProfile, generateMockAnswers, generateMockProfile } from '@/lib/categorize';
import { MOCK_RECOMMENDATIONS } from '@/mock/recommendations';
import type { Category } from '@/types';

const CATEGORY_TONES: Record<Category, 'red' | 'amber' | 'green'> = {
  Low: 'red',
  Average: 'amber',
  High: 'green',
};

const RIASEC_COLORS = ['#0d9488', '#f59e0b', '#3b82f6'];

const RANK_STYLES = [
  { bg: 'bg-amber-100', text: 'text-amber-700', border: 'border-amber-300', label: '1st' },
  { bg: 'bg-slate-100', text: 'text-slate-600', border: 'border-slate-300', label: '2nd' },
  { bg: 'bg-orange-100', text: 'text-orange-700', border: 'border-orange-300', label: '3rd' },
  { bg: 'bg-teal-50', text: 'text-teal-600', border: 'border-teal-200', label: '4th' },
  { bg: 'bg-teal-50', text: 'text-teal-600', border: 'border-teal-200', label: '5th' },
];

export function Results() {
  const { answers, statuses } = useAssessment();
  const { profile } = useProfile();
  const { thresholds } = useThresholds();
  const { user, updateProfileStatus } = useAuth();

  const hasRealData = Object.values(statuses).some((s) => s === 'completed' || s === 'in-progress');

  const effectiveAnswers = useMemo(() => {
    if (hasRealData && Object.keys(answers).length > 0) return answers;
    return generateMockAnswers();
  }, [answers, hasRealData]);

  const effectiveProfile = useMemo(() => {
    if (profile) return profile;
    if (user?.track) return generateMockProfile();
    return null;
  }, [profile, user]);

  const categorized = useMemo(
    () => categorizeProfile(effectiveAnswers, effectiveProfile, thresholds),
    [effectiveAnswers, effectiveProfile, thresholds],
  );

  if (user?.hasResults === false) {
    updateProfileStatus('hasResults', true);
  }

  const riasecSegments = categorized.riasecTop3.map((r, idx) => ({
    label: `${r.code} — ${r.trait}`,
    value: r.score,
    color: RIASEC_COLORS[idx] ?? '#94a3b8',
  }));
  const riasecCodeString = categorized.riasecTop3.map((r) => r.code).join('');

  const allAttrs = [
    ...categorized.academic,
    ...categorized.aptitude,
  ];
  const topAttrs = allAttrs
    .filter((a) => a.category === 'High')
    .sort((a, b) => b.normalizedPct - a.normalizedPct)
    .slice(0, 4);

  const handlePrint = () => window.print();

  return (
    <AppShell title="My Results">
      <div className="max-w-4xl mx-auto space-y-6 print:max-w-none">
        {/* Header */}
        <div className="flex items-start justify-between flex-wrap gap-3 print:hidden">
          <div>
            <h2 className="text-2xl font-bold text-slate-800">My Recommendations</h2>
            <p className="text-slate-500 mt-1">
              Based on your assessment results and academic profile, here are your top program matches.
            </p>
          </div>
          <button
            onClick={handlePrint}
            className="flex items-center gap-2 px-4 py-2.5 rounded-lg bg-white border border-slate-300 text-slate-700 text-sm font-semibold hover:bg-slate-50 transition-colors"
          >
            <Printer className="w-4 h-4" />
            Print / Save as PDF
          </button>
        </div>

        {/* Print-only header */}
        <div className="hidden print:block mb-4">
          <h1 className="text-2xl font-bold text-slate-900">ProPath — Program Recommendations</h1>
          <p className="text-slate-600">Student: {user?.name} | Date: {new Date().toLocaleDateString()}</p>
        </div>

        {/* Disclaimer */}
        <div className="flex items-start gap-3 p-4 rounded-xl bg-blue-50 border border-blue-200 print:hidden">
          <Info className="w-5 h-5 text-blue-600 flex-shrink-0 mt-0.5" />
          <p className="text-sm text-blue-800">
            <span className="font-semibold">Important:</span> These recommendations are generated by ProPath to
            <span className="font-semibold"> guide, not replace</span>, the Guidance Office. Please consult your
            guidance counselor before making final program decisions.
          </p>
        </div>

        {/* Profile Summary */}
        <Card className="print:border-slate-300">
          <CardHeader
            title="Your Profile Summary"
            subtitle="Academic record and categorized assessment attributes"
            icon={<TrendingUp className="w-5 h-5" />}
          />
          <div className="p-5 grid md:grid-cols-2 gap-6">
            {/* Left: GWA + RIASEC */}
            <div className="space-y-4">
              <div className="flex items-center gap-3">
                <div className="w-12 h-12 rounded-2xl bg-teal-50 flex items-center justify-center">
                  <Award className="w-6 h-6 text-teal-600" />
                </div>
                <div>
                  <p className="text-2xl font-bold text-slate-800">{categorized.gwaValue}</p>
                  <div className="flex items-center gap-2 mt-0.5">
                    <span className="text-xs text-slate-500">GWA</span>
                    <Badge tone={CATEGORY_TONES[categorized.gwaCategory]}>{categorized.gwaCategory}</Badge>
                  </div>
                </div>
              </div>

              <div>
                <div className="flex items-center gap-2 mb-2">
                  <Compass className="w-4 h-4 text-teal-600" />
                  <span className="text-sm font-semibold text-slate-700">RIASEC Code: {riasecCodeString}</span>
                </div>
                {riasecSegments.length > 0 && (
                  <DonutChart segments={riasecSegments} centerValue={riasecCodeString} centerLabel="Code" size={140} />
                )}
              </div>
            </div>

            {/* Right: Key strengths + strand */}
            <div className="space-y-4">
              <div className="flex items-center gap-2">
                <GraduationCap className="w-4 h-4 text-teal-600" />
                <span className="text-sm font-semibold text-slate-700">
                  Strand: {effectiveProfile?.strand ?? '—'}
                </span>
              </div>

              <div>
                <p className="text-sm font-semibold text-slate-700 mb-2">Key Strengths</p>
                <div className="flex flex-wrap gap-2">
                  {topAttrs.map((attr, idx) => (
                    <div
                      key={idx}
                      className="inline-flex items-center gap-2 px-3 py-1.5 rounded-lg border border-slate-200 bg-white"
                    >
                      <span className="text-sm font-medium text-slate-700">{attr.label}</span>
                      <Badge tone="green">High</Badge>
                    </div>
                  ))}
                  {topAttrs.length === 0 && (
                    <p className="text-sm text-slate-400">No High-rated attributes yet.</p>
                  )}
                </div>
              </div>

              <div>
                <p className="text-sm font-semibold text-slate-700 mb-2">Subject Performance</p>
                <BarChart
                  data={categorized.subjectCategories.map((s) => ({
                    label: s.label,
                    value: s.rawScore,
                    category: s.category,
                  }))}
                  max={99}
                  unit=""
                />
              </div>
            </div>
          </div>
        </Card>

        {/* Ranked Recommendations */}
        <div>
          <div className="flex items-center gap-2 mb-4">
            <Trophy className="w-5 h-5 text-amber-500" />
            <h3 className="text-lg font-bold text-slate-800">Top 5 Program Recommendations</h3>
          </div>

          <div className="space-y-3">
            {MOCK_RECOMMENDATIONS.map((rec) => {
              const rankStyle = RANK_STYLES[rec.rank - 1] ?? RANK_STYLES[4];
              return (
                <Card
                  key={rec.program}
                  className={`p-5 hover:shadow-md transition-shadow print:shadow-none ${rankStyle.border}`}
                >
                  <div className="flex items-start gap-4">
                    {/* Rank badge */}
                    <div
                      className={`w-14 h-14 rounded-2xl ${rankStyle.bg} flex items-center justify-center flex-shrink-0`}
                    >
                      <span className={`text-lg font-bold ${rankStyle.text}`}>#{rec.rank}</span>
                    </div>

                    {/* Content */}
                    <div className="flex-1 min-w-0">
                      <div className="flex items-start justify-between gap-2 flex-wrap">
                        <div>
                          <h4 className="font-bold text-slate-800 text-base">{rec.program}</h4>
                          <p className="text-sm text-slate-500 flex items-center gap-1 mt-0.5">
                            <Briefcase className="w-3.5 h-3.5" />
                            {rec.field}
                          </p>
                        </div>
                        <div className="text-right flex-shrink-0">
                          <div className="flex items-center gap-1.5">
                            <span className="text-2xl font-bold text-teal-600">
                              {Math.round(rec.confidence * 100)}%
                            </span>
                          </div>
                          <span className="text-xs text-slate-400">confidence</span>
                        </div>
                      </div>

                      <p className="text-sm text-slate-600 mt-2 leading-relaxed">{rec.reason}</p>

                      <div className="flex items-center gap-2 mt-3">
                        <Link
                          to={`/student/results/${rec.rank}`}
                          className="inline-flex items-center gap-1 text-sm font-semibold text-teal-700 hover:text-teal-800"
                        >
                          View Explanation
                          <ArrowRight className="w-3.5 h-3.5" />
                        </Link>
                      </div>
                    </div>
                  </div>
                </Card>
              );
            })}
          </div>
        </div>

        {/* Print-only footer disclaimer */}
        <div className="hidden print:block mt-6 pt-4 border-t border-slate-300">
          <p className="text-xs text-slate-500">
            Disclaimer: ProPath is a support tool for the Guidance Office. Recommendations are generated from
            assessment and academic data to guide counseling — not replace it. Please consult your guidance counselor.
          </p>
        </div>
      </div>
    </AppShell>
  );
}
